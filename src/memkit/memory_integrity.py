#!/usr/bin/env python3
"""Check (or regenerate) the memory stores' layout, ledgers, and frontmatter.

Plain `python3`, not the `uv run --script` shebang the rest of this author's
Python carries. A deliberate one-file break with that convention: a consumer of
memkit cannot be assumed to have uv, and this script is the one piece an
adopter may want to run from a git hook or a bare CI image. The floor is still
3.12 — see the version guard below, which exists so an older interpreter says
so by name instead of dying on a syntax error nobody can read.

Tier is PATH, not frontmatter. Each store contains exactly:

    MEMORY.md   hot ledger — auto-loaded every session, hand-curated
    SEARCH.md   search ledger — never loaded, GENERATED by this script
    hot/        hot memories (one MEMORY.md row each)
    search/     retrieval-only memories, incl. domain sub-dirs like
                search/<domain>/ whose INDEX.md ledgers its own subtree
    archive/    dead memories: no tier, no row, not retrieved

A `tier:` frontmatter key is an error: it was the old source of truth and
two sources of truth for the same fact is how they drift. The recall hook
reads the same layout (it roots retrieval at `<store>/search`), so a file's
directory decides whether it is in context already or discoverable by search —
nothing else does.

SEARCH.md and the sub-indexes are generated: `--write` rewrites every row
from the corresponding file's frontmatter `description:`, alphabetically by
label, plus the "(N memories)" counts. Check mode fails on any drift. Hot
rows stay hand-written — a hot row is a judgement about what deserves to be
in context, which no generator can make — but a hot file edited after its
row was last touched draws a staleness warning.

Every markdown link that names a file must resolve on disk (DEAD-LINK), and
every wikilink should name a memory that exists (DANGLING-WIKILINK, a warning
— a dangling one is the store's way of marking a memory worth writing). Repo
paths cited in PROSE must resolve too (DEAD-PATH). Those fail the run only in
the memories the current commit touches, whatever else was read: `--all`
widens the scan to the whole store and reports the rest as warnings, so an
audit still surfaces drift without failing whoever happened to run it.

Which trees to check comes from the config file (`--config`, else
MEMKIT_CONFIG), and for each store it is the EDIT tree — `edit_root`, the tree
whose changes are being verified — not the live copy the recall hook serves.
Run from a worktree, this checks and rewrites that worktree. Exits 0 if all
stores are consistent; 1 otherwise.
"""

